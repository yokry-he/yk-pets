#!/usr/bin/env node
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const read = path => readFileSync(path, 'utf8')
const authoring = read('packages/pet-core/src/motion/simple-motion-authoring.ts')
const compiler = read('packages/pet-core/src/motion/simple-motion-compiler.ts')
const assets = read('apps/playground/app/stores/studio-assets.ts')
const editor = read('apps/playground/app/stores/studio-motion-editor.ts')
const picker = read('apps/playground/app/components/studio/StudioMotionIntentPicker.vue')
const stages = read('apps/playground/app/components/studio/StudioMotionStageBar.vue')
const inspector = read('apps/playground/app/components/studio/StudioMotionStageInspector.vue')
const transformEditor = read('apps/playground/app/components/studio/StudioMotionTransformEditor.vue')
const page = read('apps/playground/app/pages/studio/motion.vue')

assert.match(authoring, /SIMPLE_MOTION_AUTHORING_EXTENSION_KEY/)
assert.match(authoring, /createSimpleMotionRecipe/)
assert.match(compiler, /compileSimpleMotionRecipe/)
assert.match(compiler, /SIMPLE_MOTION_CORRECTION_LAYER_ID/)
assert.match(assets, /createMotionFromIntent\(intent: SimpleMotionIntent/)
assert.match(assets, /compileSimpleMotionRecipe/)
assert.match(editor, /selectedStageId:/)
assert.match(editor, /authoringMode: 'guided'/)
assert.match(editor, /updateSimpleStage/)
assert.match(editor, /selectSimpleStage/)
assert.match(editor, /duplicateSimpleStage/)
assert.match(editor, /moveSimpleStage/)
assert.match(editor, /removeSimpleStage/)
assert.ok(['日常', '舞蹈', '功夫', '运动', '自定义'].every(label => picker.includes(label)))
assert.match(picker, /创建\$\{item\.labelZh\}动作/)
assert.match(stages, /复制阶段/)
assert.match(stages, /删除阶段/)
assert.match(stages, /aria-current/)
assert.ok(['姿势', '节奏', '效果'].every(label => inspector.includes(label)))
assert.match(inspector, /StudioMotionTransformEditor/)
assert.match(transformEditor, /guided/)
assert.match(page, /StudioMotionIntentPicker/)
assert.match(page, /StudioMotionStageBar/)
assert.match(page, /StudioMotionStageInspector/)
assert.match(page, /高级编辑/)
assert.match(page, /返回简易编辑/)
assert.match(page, /scheduleAutoSave/)
assert.match(page, /500/)
assert.match(page, /正在保存/)
assert.match(page, /保存失败/)

console.log('Simple motion authoring gate passed.')
